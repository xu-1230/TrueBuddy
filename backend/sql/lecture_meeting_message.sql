-- =============================================================
-- TrueBuddy - 模拟会议消息表 lecture_meeting_message
-- 对应讲课模块 tb-module-lecture（meeting 包）
-- 说明：
--   1. 学生文字提问与老师发言均落本表，默认广播给全体参会者；
--   2. kind 为后续「语音转写」与「数字人发言」预留，本期只用 1=文字；
--   3. 从属表按会议物理删除，不做单独软删语义之外的处理。
-- =============================================================

CREATE TABLE IF NOT EXISTS lecture_meeting_message (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    meeting_id  BIGINT      NOT NULL,                    -- 会议 id（逻辑外键 lecture_meeting.id）
    attendee_id BIGINT,                                  -- 发送人 id（逻辑外键 lecture_meeting_attendee.id）
    nickname    VARCHAR(64) NOT NULL,                    -- 发送人昵称（冗余存储，便于直接渲染）
    role        SMALLINT    NOT NULL DEFAULT 2,          -- 发送人角色：1=老师，2=学生
    content     TEXT        NOT NULL,                    -- 消息正文
    kind        SMALLINT    NOT NULL DEFAULT 1,          -- 消息类型：1=文字（2/3 预留给语音转写与数字人）
    create_time TIMESTAMP   NOT NULL DEFAULT now(),      -- 创建时间
    update_time TIMESTAMP   NOT NULL DEFAULT now(),      -- 更新时间
    creator     BIGINT,                                  -- 创建人 id
    updater     BIGINT,                                  -- 更新人 id
    deleted     BOOLEAN     NOT NULL DEFAULT FALSE,      -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE  lecture_meeting_message IS '模拟会议消息表（学生提问与老师发言）';
COMMENT ON COLUMN lecture_meeting_message.meeting_id IS '会议 id（逻辑外键 lecture_meeting.id）';
COMMENT ON COLUMN lecture_meeting_message.attendee_id IS '发送人 id（逻辑外键 lecture_meeting_attendee.id）';
COMMENT ON COLUMN lecture_meeting_message.nickname IS '发送人昵称（冗余存储）';
COMMENT ON COLUMN lecture_meeting_message.role IS '发送人角色：1=老师，2=学生';
COMMENT ON COLUMN lecture_meeting_message.content IS '消息正文';
COMMENT ON COLUMN lecture_meeting_message.kind IS '消息类型：1=文字（2/3 预留给语音转写与数字人发言）';

-- 拉取某会议的消息（按 id 递增即时间序）
CREATE INDEX IF NOT EXISTS idx_lecture_meeting_message_meeting
    ON lecture_meeting_message (meeting_id, id) WHERE deleted = FALSE;
