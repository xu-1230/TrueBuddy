-- =============================================================
-- TrueBuddy - 知识库文档分片表 kb_document_chunk
-- 定位：AI 语义分片的持久化产物
-- 说明：
--   1. 不存类型与标题，类型属于版面块（kb_document_parse_block.block_type）；
--   2. 从属表，重解析时物理删除重建，不做软删除。
-- =============================================================

CREATE TABLE IF NOT EXISTS kb_document_chunk (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    document_id   BIGINT       NOT NULL,                   -- 所属文档 id（kb_document.id）
    space_id      BIGINT       NOT NULL,                   -- 冗余空间 id，便于按空间过滤

    chunk_index   INTEGER      NOT NULL,                   -- 分片序号（从 0 开始）
    content       TEXT         NOT NULL,                   -- 分片正文
    token_count   INTEGER      NOT NULL DEFAULT 0,         -- token 数

    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,      -- 是否参与检索（单条分片启停，替代删除）
    hit_count     INTEGER      NOT NULL DEFAULT 0,         -- 召回次数

    create_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator       BIGINT,                                  -- 创建人 id
    updater       BIGINT,                                  -- 更新人 id
    PRIMARY KEY (id)
);

COMMENT ON TABLE  kb_document_chunk IS '知识库文档分片表（AI 语义分片产物）';
COMMENT ON COLUMN kb_document_chunk.space_id  IS '冗余空间 id，便于按空间过滤';
COMMENT ON COLUMN kb_document_chunk.enabled   IS '是否参与检索（单条分片启停，替代删除）';

-- 同一文档下分片序号唯一（物理删除重建，故不加 deleted 条件）
CREATE UNIQUE INDEX IF NOT EXISTS uk_kb_document_chunk
    ON kb_document_chunk (document_id, chunk_index);
CREATE INDEX IF NOT EXISTS idx_kb_document_chunk_space
    ON kb_document_chunk (space_id);
