-- =============================================================
-- TrueBuddy - 知识库文档分片表 kb_document_chunk
-- 对应前端 ChunkVO（index 即 chunk_index）
-- =============================================================

CREATE TABLE IF NOT EXISTS kb_document_chunk (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    document_id BIGINT       NOT NULL,                   -- 所属文档 id（kb_document.id）
    chunk_index INTEGER      NOT NULL,                   -- 分片序号（从 0 开始）
    title       VARCHAR(255),                            -- 分片标题
    content     TEXT         NOT NULL,                   -- 分片正文
    create_time TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator     BIGINT,                                  -- 创建人 id
    updater     BIGINT,                                  -- 更新人 id
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE kb_document_chunk IS '知识库文档分片表';

-- 同一文档下分片序号唯一（仅约束未删除记录，便于重新解析覆盖）
CREATE UNIQUE INDEX uk_kb_document_chunk ON kb_document_chunk (document_id, chunk_index) WHERE deleted = FALSE;
CREATE INDEX idx_kb_document_chunk_document_id ON kb_document_chunk (document_id);
