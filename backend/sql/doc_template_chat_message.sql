-- =============================================================
-- TrueBuddy - 文档 AI 聊天消息表 doc_template_chat_message
-- 说明：
--   1. 聊天记录归属根文件（doc_template_file.id，即文档工作区）；
--   2. role：user / assistant / system；
--   3. content 为扁平文本，供 LLM 上下文与兜底展示；
--   4. blocks 为助手结构化回复（p / ul 块），selections 为用户消息的选区；
--   5. version_id 指向本次编辑生成的 doc_template_version 行，无编辑为 NULL；
--   6. 撤回时目标助手消息及其后消息置 superseded，刷新后仍显示「已失效」；
--   7. creator 为发送人；记录只对根文件 creator 可见。
-- =============================================================

CREATE TABLE IF NOT EXISTS doc_template_chat_message (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    root_file_id BIGINT      NOT NULL,                    -- 工作区（doc_template_file.id）
    role         VARCHAR(16) NOT NULL,                    -- user / assistant / system
    content      TEXT        NOT NULL,                    -- 扁平文本
    blocks       JSONB,                                   -- 助手结构化回复块
    selections   JSONB,                                   -- 用户消息的选区上下文
    version_id   BIGINT,                                  -- 本次编辑产生的版本 id
    superseded   BOOLEAN     NOT NULL DEFAULT FALSE,      -- 撤回后失效
    error        BOOLEAN     NOT NULL DEFAULT FALSE,      -- 失败回复
    creator      BIGINT,                                  -- 发送人（system_user.id）
    create_time  TIMESTAMP   NOT NULL DEFAULT now(),      -- 创建时间
    PRIMARY KEY (id)
);

COMMENT ON TABLE  doc_template_chat_message IS '文档 AI 聊天消息表（按根文件归属）';
COMMENT ON COLUMN doc_template_chat_message.root_file_id IS '工作区（doc_template_file.id）';
COMMENT ON COLUMN doc_template_chat_message.role IS '消息角色：user / assistant / system';
COMMENT ON COLUMN doc_template_chat_message.content IS '扁平文本（LLM 上下文 / 兜底展示）';
COMMENT ON COLUMN doc_template_chat_message.blocks IS '助手结构化回复块（p / ul）';
COMMENT ON COLUMN doc_template_chat_message.selections IS '用户消息的选区上下文';
COMMENT ON COLUMN doc_template_chat_message.version_id IS '本次编辑产生的 doc_template_version.id；无编辑为 NULL';
COMMENT ON COLUMN doc_template_chat_message.superseded IS '撤回后失效（目标消息及其后消息）';
COMMENT ON COLUMN doc_template_chat_message.error IS '失败回复';

-- 按文档取最近记录
CREATE INDEX IF NOT EXISTS idx_doc_template_chat_message_root
    ON doc_template_chat_message (root_file_id, id);

-- 按版本回溯撤回目标（只索引有版本的消息）
CREATE INDEX IF NOT EXISTS idx_doc_template_chat_message_root_version
    ON doc_template_chat_message (root_file_id, version_id) WHERE version_id IS NOT NULL;
