-- =============================================================
-- TrueBuddy - 知识库文档解析版面块表 kb_document_parse_block
-- 定位：docmind 解析结果的持久化产物（块级），AI 语义分片的输入
-- 关系：kb_document 1 ── N kb_document_parse_block
-- 策略：从属表，重解析时物理删除重建，不做软删除
-- =============================================================

CREATE TABLE IF NOT EXISTS kb_document_parse_block (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    document_id    BIGINT       NOT NULL,                   -- 所属文档 id（kb_document.id）
    space_id       BIGINT       NOT NULL,                   -- 冗余空间 id，便于按空间过滤

    block_index    INTEGER      NOT NULL,                   -- 全局阅读顺序（从 0 开始）
    page_num       INTEGER,                                 -- 页码（LayoutVO.pageNum）
    page_block_seq INTEGER,                                 -- 页内序号（LayoutVO.index）

    block_type     VARCHAR(50)  NOT NULL,                   -- 版面类型，取值开放
    content        TEXT         NOT NULL,                   -- 块的 Markdown 正文
    text           TEXT,                                    -- 块的纯文本（可能为空）
    external_id    VARCHAR(64),                             -- 解析引擎块 ID（LayoutVO.uniqueId）
    token_count    INTEGER      NOT NULL DEFAULT 0,         -- 估算 token 数

    create_time    TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    PRIMARY KEY (id)
);

COMMENT ON TABLE  kb_document_parse_block IS '知识库文档解析版面块表（解析产物，持久化）';
COMMENT ON COLUMN kb_document_parse_block.block_index    IS '全局阅读顺序（从 0 开始，即 AI 分片的输入顺序）';
COMMENT ON COLUMN kb_document_parse_block.page_num       IS '页码（LayoutVO.pageNum）';
COMMENT ON COLUMN kb_document_parse_block.page_block_seq IS '页内序号（LayoutVO.index）';
COMMENT ON COLUMN kb_document_parse_block.block_type     IS '版面类型，取值开放（title/text/table/figure...），不做枚举约束';
COMMENT ON COLUMN kb_document_parse_block.content        IS '块的 Markdown 正文（LayoutVO.markdownContent）';
COMMENT ON COLUMN kb_document_parse_block.text           IS '块的纯文本（LayoutVO.text），Markdown 缺失时作降级';
COMMENT ON COLUMN kb_document_parse_block.external_id    IS '解析引擎返回的块唯一 ID（LayoutVO.uniqueId），用于溯源';

-- 同一文档内块顺序唯一；按 document_id 的查询与删除走这个唯一键的最左前缀，无需再建单列索引
CREATE UNIQUE INDEX IF NOT EXISTS uk_parse_block_doc_index
    ON kb_document_parse_block (document_id, block_index);
-- 旧版单列索引是上面的严格左前缀，已建库执行时顺手清掉
DROP INDEX IF EXISTS idx_parse_block_doc;
-- 按空间统计与过滤
CREATE INDEX IF NOT EXISTS idx_parse_block_space
    ON kb_document_parse_block (space_id);
