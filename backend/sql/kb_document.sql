-- =============================================================
-- TrueBuddy - 知识库文档表 kb_document
-- 已合并原 kb_document_alter_docmind.sql 的解析相关字段（该文件已废弃删除）
-- 说明：
--   1. 原文不落库，整篇 Markdown 由 kb_document_parse_block 聚合得到；
--   2. 删除状态用 deleted_at 表示（NULL = 未删除），不再使用 deleted 布尔列。
-- =============================================================

CREATE TABLE IF NOT EXISTS kb_document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    space_id         BIGINT       NOT NULL,                   -- 所属空间 id（kb_space.id）
    file_id          BIGINT,                                  -- 关联文件 id（infra_file.id，可空）
    name             VARCHAR(255) NOT NULL,                   -- 文档名称
    type             VARCHAR(20)  NOT NULL,                   -- 文档类型：PDF / WORD / MARKDOWN

    chunk_count      INTEGER      NOT NULL DEFAULT 0,         -- 分片数量
    token_count      INTEGER      NOT NULL DEFAULT 0,         -- 文档 token 总量

    status           SMALLINT     NOT NULL DEFAULT 0,         -- 处理状态，见下方 COMMENT
    docmind_job_id   VARCHAR(64),                             -- 解析任务句柄
    parse_progress   SMALLINT     NOT NULL DEFAULT 0,         -- 解析进度 0-100
    parse_error      TEXT,                                    -- 解析失败原因

    parse_start_at   TIMESTAMP,                               -- 解析开始时间
    parse_end_at     TIMESTAMP,                               -- 解析结束时间
    vectorize_at     TIMESTAMP,                               -- 向量化完成时间

    create_time      TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time      TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator          BIGINT,                                  -- 创建人 id
    updater          BIGINT,                                  -- 更新人 id
    deleted_at       TIMESTAMP,                               -- 删除时间，NULL=未删除

    PRIMARY KEY (id)
);

COMMENT ON TABLE  kb_document IS '知识库文档表';
COMMENT ON COLUMN kb_document.deleted_at IS '删除时间，NULL 表示未删除';
COMMENT ON COLUMN kb_document.docmind_job_id IS '解析任务句柄：云端为文档智能业务订单号，本地为内存任务 id';
COMMENT ON COLUMN kb_document.parse_error IS '解析失败原因';
COMMENT ON COLUMN kb_document.status IS
    '处理状态：0=待处理，1=解析中，2=已完成（已向量化），3=失败，4=分片待确认，5=解析完成待分片，6=AI分片中，7=向量化中';

-- 列表 / 计数 / 聚合共用（仅约束未删除记录）
CREATE INDEX IF NOT EXISTS idx_kb_document_space_status
    ON kb_document (space_id, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_kb_document_file_id
    ON kb_document (file_id);
