-- =============================================================
-- TrueBuddy - 教师数字人与音色偏好表 lecture_avatar_preference
-- 对应讲课模块 tb-module-lecture（PPT 数字人设置）
-- 说明：
--   1. 一个登录用户一行；avatar_model_code 对应 avatar_model.model_code，
--      voice_code 对应 avatar_voice.voice_code（两者都可为空，表示使用默认）；
--   2. 未删除记录内 creator 唯一（部分唯一索引）；
--   3. 软删用 deleted 布尔列（与 lecture_meeting 一致）；creator / updater 为逻辑外键。
-- =============================================================

CREATE TABLE IF NOT EXISTS lecture_avatar_preference (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    creator           BIGINT       NOT NULL,                   -- 用户 id（system_user.id）
    avatar_model_code VARCHAR(50),                             -- 当前选中的形象编码，空=默认形象
    voice_code        VARCHAR(128),                            -- 当前选中的音色编码，空=默认音色
    create_time       TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time       TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    updater           BIGINT,                                  -- 更新人 id
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE  lecture_avatar_preference IS '教师数字人与音色偏好（一个用户一行）';
COMMENT ON COLUMN lecture_avatar_preference.creator IS '用户 id（system_user.id）';
COMMENT ON COLUMN lecture_avatar_preference.avatar_model_code IS '当前选中的形象编码，空=默认形象';
COMMENT ON COLUMN lecture_avatar_preference.voice_code IS '当前选中的音色编码，空=默认音色';

CREATE UNIQUE INDEX IF NOT EXISTS uk_lecture_avatar_preference_creator
    ON lecture_avatar_preference (creator) WHERE deleted = FALSE;
