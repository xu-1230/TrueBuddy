-- =============================================================
-- TrueBuddy - 用户表 system_user
-- 字段与 AdminUserDO 对齐（module.test.model.AdminUserDO）
-- =============================================================

CREATE TABLE IF NOT EXISTS "system_user" (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    username   VARCHAR(30)  NOT NULL,                   -- 登录账号
    password   VARCHAR(100) NOT NULL,                   -- 登录密码（加密存储）
    nickname   VARCHAR(30),                             -- 用户昵称
    remark     VARCHAR(500),                            -- 备注
    email      VARCHAR(50),                             -- 邮箱
    avatar     VARCHAR(512),                            -- 头像 URL
    status     INTEGER      NOT NULL DEFAULT 0,         -- 状态：0=正常，1=禁用
    login_ip   VARCHAR(50),                             -- 最后登录 IP
    login_date TIMESTAMP,                               -- 最后登录时间
    PRIMARY KEY (id)
);

COMMENT ON TABLE "system_user" IS '用户表';

-- 用户名唯一
CREATE UNIQUE INDEX uk_system_user_username ON "system_user" (username);

-- 邮箱唯一（PostgreSQL 允许多个 NULL，未填邮箱的账号不受影响）
CREATE UNIQUE INDEX IF NOT EXISTS uk_system_user_email ON "system_user" (email);