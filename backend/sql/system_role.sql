-- =============================================================
-- TrueBuddy - 角色表 system_role
-- =============================================================

CREATE TABLE IF NOT EXISTS system_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    name        VARCHAR(30)  NOT NULL,                   -- 角色名称
    code        VARCHAR(100) NOT NULL,                   -- 角色编码
    status      SMALLINT     NOT NULL DEFAULT 0,         -- 状态：0=正常，1=禁用
    remark      VARCHAR(500),                            -- 备注
    PRIMARY KEY (id)
);

COMMENT ON TABLE system_role IS '角色表';

-- 角色编码唯一
CREATE UNIQUE INDEX uk_system_role_code ON system_role (code);