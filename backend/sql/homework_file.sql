-- =============================================================
-- TrueBuddy - 作业文件表 homework_file
-- 对应作业批改模块 tb-module-homework
-- 说明：
--   1. 任务下的每一份作业；file_id 关联 infra_file.id（逻辑外键，不建约束）；
--   2. relative_path 为本模块的产出核心，形如：
--      电子技术基础-第3次作业/20230101-张三/第三章习题.docx
--      （infra_file 只存基础文件名，路径信息无法由它还原，故单独落此表）；
--   3. 从属表采用物理删除，不设软删列。
-- =============================================================

CREATE TABLE IF NOT EXISTS homework_file (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    task_id       BIGINT       NOT NULL,                   -- 所属任务 id（homework_task.id）
    file_id       BIGINT,                                  -- 关联文件 id（infra_file.id，可空）
    relative_path VARCHAR(512) NOT NULL,                   -- 相对路径（含根目录，/ 分隔）
    name          VARCHAR(255) NOT NULL,                   -- 文件基础名（含扩展名）
    size          BIGINT       NOT NULL DEFAULT 0,         -- 文件大小（字节）
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    PRIMARY KEY (id)
);

COMMENT ON TABLE  homework_file IS '作业文件表（任务下每份作业）';
COMMENT ON COLUMN homework_file.task_id IS '所属任务 id（homework_task.id）';
COMMENT ON COLUMN homework_file.file_id IS '关联文件 id（infra_file.id，逻辑外键）';
COMMENT ON COLUMN homework_file.relative_path IS '相对路径，如 电子技术基础-第3次作业/20230101-张三/第三章习题.docx';
COMMENT ON COLUMN homework_file.name IS '文件基础名（含扩展名）';
COMMENT ON COLUMN homework_file.size IS '文件大小（字节）';

-- 按任务读取（目录树阅读顺序由 ORDER BY relative_path 决定）
CREATE INDEX IF NOT EXISTS idx_homework_file_task_id
    ON homework_file (task_id);
-- 同一任务内相对路径唯一
CREATE UNIQUE INDEX IF NOT EXISTS uk_homework_file_task_path
    ON homework_file (task_id, relative_path);
