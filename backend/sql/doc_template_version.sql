-- =============================================================
-- TrueBuddy - 文档编辑版本表 doc_template_version
-- 对应文档模板 AI 聊天真实编辑链路
-- 说明：
--   1. 根文件（doc_template_file 根行）即工作区，也是 v1；本表只存 v2+ 的不可变版本；
--   2. parent_version_id 为空表示从 v1 根文件继续；
--   3. doc_template_file.current_version_id 指向当前版本；为空表示当前是 v1 根文件；
--   4. 撤回时目标版本及其所有后代置 superseded，current_version_id 回到 parent_version_id；
--   5. creator 为执行这次编辑的用户；只有根文件 creator 可以编辑/撤回。
-- =============================================================

CREATE TABLE IF NOT EXISTS doc_template_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    root_file_id      BIGINT       NOT NULL,                   -- 根文件 id（doc_template_file.id，即工作区）
    file_id           BIGINT       NOT NULL,                   -- 该版本 docx（infra_file.id）
    parent_version_id BIGINT,                                  -- 父版本 id；NULL 表示父级是 v1 根文件
    revision          INTEGER      NOT NULL,                   -- 版本号（2、3…；v1 不在本表）
    edit_summary      VARCHAR(500),                            -- 本次修改摘要（审计 / 撤回提示）
    edit_ops          JSONB,                                   -- 结构化编辑指令（审计用）
    creator           BIGINT,                                  -- 编辑人 id（system_user.id）
    create_time       TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    superseded        BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否已被撤回 / 级联失效
    PRIMARY KEY (id)
);

COMMENT ON TABLE doc_template_version IS '文档编辑版本表（根文件即 v1，本表存 v2+）';
COMMENT ON COLUMN doc_template_version.root_file_id IS '根文件 id（doc_template_file.id，即工作区）';
COMMENT ON COLUMN doc_template_version.parent_version_id IS '父版本 id；NULL 表示父级为 v1 根文件';
COMMENT ON COLUMN doc_template_version.revision IS '版本号：2、3…；v1 由根文件承担';
COMMENT ON COLUMN doc_template_version.superseded IS '撤回时目标版本及其后代置 TRUE';

CREATE UNIQUE INDEX IF NOT EXISTS uk_doc_template_version_root_revision
    ON doc_template_version (root_file_id, revision);

CREATE INDEX IF NOT EXISTS idx_doc_template_version_parent
    ON doc_template_version (parent_version_id);

CREATE INDEX IF NOT EXISTS idx_doc_template_version_root
    ON doc_template_version (root_file_id, superseded);
