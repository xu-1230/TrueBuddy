-- 2026-11-17 文档 AI 聊天真实接入：版本表 + 当前版本指针 + 存量归属
--
-- 幂等：可重复执行。
-- 1. doc_template_file 增加 current_version_id（NULL = 根文件 v1）
-- 2. 新增 doc_template_version（与 doc_template_version.sql 保持一致）
-- 3. 存量 doc_template_generation / doc_template_file 的 creator 统一刷为
--    2902017108@qq.com（system_user.id）；新生成由应用写入当前登录用户。
-- =============================================================

BEGIN;

ALTER TABLE doc_template_file ADD COLUMN IF NOT EXISTS current_version_id BIGINT;
COMMENT ON COLUMN doc_template_file.current_version_id IS '当前版本（doc_template_version.id）；NULL 表示根文件本身即 v1';

CREATE TABLE IF NOT EXISTS doc_template_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    root_file_id      BIGINT       NOT NULL,
    file_id           BIGINT       NOT NULL,
    parent_version_id BIGINT,
    revision          INTEGER      NOT NULL,
    edit_summary      VARCHAR(500),
    edit_ops          JSONB,
    creator           BIGINT,
    create_time       TIMESTAMP    NOT NULL DEFAULT now(),
    superseded        BOOLEAN      NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id)
);

COMMENT ON TABLE doc_template_version IS '文档编辑版本表（根文件即 v1，本表存 v2+）';
COMMENT ON COLUMN doc_template_version.root_file_id IS '根文件 id（doc_template_file.id，即工作区）';
COMMENT ON COLUMN doc_template_version.parent_version_id IS '父版本 id；NULL 表示父级为 v1 根文件';
COMMENT ON COLUMN doc_template_version.revision IS '版本号：2、3…；v1 由根文件承担';
COMMENT ON COLUMN doc_template_version.superseded IS '撤回时目标版本及其后代置 TRUE';

CREATE UNIQUE INDEX IF NOT EXISTS uk_doc_template_version_root_revision
    ON doc_template_version (root_file_id, revision);

CREATE INDEX IF NOT EXISTS idx_doc_template_version_parent
    ON doc_template_version (parent_version_id);

CREATE INDEX IF NOT EXISTS idx_doc_template_version_root
    ON doc_template_version (root_file_id, superseded);

-- 存量归属：统一归入 2902017108@qq.com（id=1）。新生成由应用写入登录用户。
DO $$
DECLARE
    owner_id BIGINT;
BEGIN
    SELECT id INTO owner_id
      FROM "system_user"
     WHERE email = '2902017108@qq.com'
     LIMIT 1;
    IF owner_id IS NULL THEN
        owner_id := 1;
    END IF;

    UPDATE doc_template_generation SET creator = owner_id WHERE creator IS NULL;
    UPDATE doc_template_file       SET creator = owner_id WHERE creator IS NULL;
END
$$;

COMMIT;
