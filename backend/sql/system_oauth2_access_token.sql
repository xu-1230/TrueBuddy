-- =============================================================
-- TrueBuddy - OAuth2 访问令牌表 system_oauth2_access_token
-- 字段与 OAuth2AccessTokenDO 对齐（module.test.model.OAuth2AccessTokenDO）
-- =============================================================

CREATE TABLE IF NOT EXISTS system_oauth2_access_token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    access_token  VARCHAR(255) NOT NULL,                   -- 访问令牌
    refresh_token VARCHAR(255) NOT NULL,                   -- 关联的刷新令牌
    user_id       BIGINT       NOT NULL,                   -- 用户 id
    user_type     INTEGER      NOT NULL DEFAULT 0,         -- 已废弃：身份改由 roles/permissions 表达，代码不再读写
    user_info     JSONB,                                   -- 用户信息（冗余存储）
    scopes        JSONB,                                   -- 授权范围
    expires_time  TIMESTAMP    NOT NULL,                   -- 过期时间
    PRIMARY KEY (id)
);

COMMENT ON TABLE system_oauth2_access_token IS 'OAuth2 访问令牌表';

-- 访问令牌唯一
CREATE UNIQUE INDEX IF NOT EXISTS uk_system_oauth2_access_token
    ON system_oauth2_access_token (access_token);

-- 按用户清理（deleteByUserId）与过期清理的扫描列
CREATE INDEX IF NOT EXISTS idx_system_oauth2_access_token_user_id
    ON system_oauth2_access_token (user_id);
CREATE INDEX IF NOT EXISTS idx_system_oauth2_access_token_expires_time
    ON system_oauth2_access_token (expires_time);