-- =============================================================
-- TrueBuddy - 文档模板生成表（模板复刻）
--   doc_template_generation : 每次「生成」任务
--   doc_template_file       : 任务产出的结果文档（逻辑关联 infra_file.id）
-- 对应前端 DocTemplateView：结果卡片 + 历史记录抽屉
-- =============================================================

CREATE TABLE IF NOT EXISTS doc_template_generation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    template_file_id BIGINT       NOT NULL,                   -- 模板文件 id（infra_file.id）
    space_id         BIGINT,                                  -- 知识库空间 id（kb_space.id，为空表示不启用检索）
    description      VARCHAR(500) NOT NULL,                   -- AI 描述说明
    quality          VARCHAR(20),                             -- 清晰度参数：480p / 720p / 1080p
    doc_count        INTEGER      NOT NULL DEFAULT 0,         -- 实际产出文档数量
    status           SMALLINT     NOT NULL DEFAULT 0,         -- 任务状态：0=生成中，1=成功，2=部分成功，3=失败
    error_msg        VARCHAR(500),                            -- 失败/部分失败的错误摘要
    duration_ms      BIGINT,                                  -- 任务耗时（毫秒）
    create_time      TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time      TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator          BIGINT,                                  -- 创建人 id
    updater          BIGINT,                                  -- 更新人 id
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE doc_template_generation IS '文档模板生成任务表';

CREATE INDEX idx_doc_template_generation_template_file_id ON doc_template_generation (template_file_id);
CREATE INDEX idx_doc_template_generation_space_id ON doc_template_generation (space_id);

CREATE TABLE IF NOT EXISTS doc_template_file (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    generation_id BIGINT       NOT NULL,                   -- 所属生成任务 id（doc_template_generation.id）
    file_id       BIGINT       NOT NULL,                   -- 结果文件 id（infra_file.id）
    name          VARCHAR(255) NOT NULL,                   -- 结果文件名（含扩展名）
    type          VARCHAR(20)  NOT NULL DEFAULT 'WORD',    -- 文档类型：WORD / PDF / MARKDOWN
    size          BIGINT       NOT NULL DEFAULT 0,         -- 文件大小（字节）
    tag           VARCHAR(50),                             -- 份数定位标签：复刻 / 优化 / 精简…
    summary       VARCHAR(500),                            -- 内容摘要（结果卡片副标题）
    sort          INTEGER      NOT NULL DEFAULT 0,         -- 展示顺序（0 起）
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator       BIGINT,                                  -- 创建人 id
    updater       BIGINT,                                  -- 更新人 id
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE doc_template_file IS '文档模板生成结果文件表';

CREATE INDEX idx_doc_template_file_generation_id ON doc_template_file (generation_id);
CREATE INDEX idx_doc_template_file_file_id ON doc_template_file (file_id);
