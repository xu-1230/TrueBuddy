-- =============================================================
-- TrueBuddy - 知识库空间表 kb_space
-- 对应前端 SpaceVO（documentCount 由 kb_document 统计得出，不落库）
-- =============================================================

CREATE TABLE IF NOT EXISTS kb_space (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    name        VARCHAR(100) NOT NULL,                   -- 空间名称
    description VARCHAR(500),                            -- 空间描述
    create_time TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator     BIGINT,                                  -- 创建人 id
    updater     BIGINT,                                  -- 更新人 id
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE kb_space IS '知识库空间表';

-- 空间名称唯一（仅约束未删除记录，删除后可复用同名）
CREATE UNIQUE INDEX uk_kb_space_name ON kb_space (name) WHERE deleted = FALSE;
