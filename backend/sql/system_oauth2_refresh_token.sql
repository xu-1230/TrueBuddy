-- =============================================================
-- TrueBuddy - OAuth2 刷新令牌表 system_oauth2_refresh_token
-- 字段与 OAuth2RefreshTokenDO 对齐（module.test.model.OAuth2RefreshTokenDO）
-- =============================================================

CREATE TABLE IF NOT EXISTS system_oauth2_refresh_token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    refresh_token VARCHAR(255) NOT NULL,                   -- 刷新令牌
    user_id       BIGINT       NOT NULL,                   -- 用户 id
    user_type     INTEGER      NOT NULL DEFAULT 0,         -- 已废弃：身份改由 roles/permissions 表达，代码不再读写
    scopes        JSONB,                                   -- 授权范围
    expires_time  TIMESTAMP    NOT NULL,                   -- 过期时间
    PRIMARY KEY (id)
);

COMMENT ON TABLE system_oauth2_refresh_token IS 'OAuth2 刷新令牌表';

-- 刷新令牌唯一
CREATE UNIQUE INDEX uk_system_oauth2_refresh_token ON system_oauth2_refresh_token (refresh_token);