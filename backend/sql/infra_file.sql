-- =============================================================
-- TrueBuddy - 文件表 infra_file（MinIO 对象元数据）
-- 存储端：MinIO（endpoint/bucket 等见 tb-server application.yml）
--   tb.file.minio.endpoint    : http://localhost:9000
--   tb.file.minio.access-key  : admin
--   tb.file.minio.secret-key  : ${MINIO_SECRET_KEY}（真实值在 backend/.env，gitignored）
--   tb.file.minio.bucket      : test-bucket
-- =============================================================

CREATE TABLE IF NOT EXISTS infra_file (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    bucket      VARCHAR(100) NOT NULL,                   -- 存储桶（MinIO bucket，如 test-bucket）
    path        VARCHAR(512) NOT NULL,                   -- 对象键（MinIO objectKey，如 kb/2026/09/uuid.pdf）
    name        VARCHAR(255) NOT NULL,                   -- 原始文件名（含扩展名）
    url         VARCHAR(1024),                           -- 访问地址（MinIO 直链/预签名 URL）
    size        BIGINT       NOT NULL DEFAULT 0,         -- 文件大小（字节）
    type        VARCHAR(100),                            -- 文件类型（MIME，如 application/pdf）
    create_time TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator     BIGINT,                                  -- 创建人 id
    updater     BIGINT,                                  -- 更新人 id
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE infra_file IS '文件表（MinIO 对象元数据）';

-- 同一桶内对象键唯一（仅约束未删除记录）
CREATE UNIQUE INDEX uk_infra_file_bucket_path ON infra_file (bucket, path) WHERE deleted = FALSE;
