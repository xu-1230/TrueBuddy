-- =============================================================
-- TrueBuddy - 菜单权限表 system_menu
-- =============================================================

CREATE TABLE IF NOT EXISTS system_menu (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    name        VARCHAR(50)  NOT NULL,                   -- 菜单名称
    parent_id   BIGINT       NOT NULL DEFAULT 0,         -- 父菜单 id（0=根节点）
    type        SMALLINT     NOT NULL DEFAULT 1,         -- 菜单类型：1=目录，2=菜单，3=按钮
    path        VARCHAR(200),                            -- 路由地址
    component   VARCHAR(200),                            -- 组件路径
    permission  VARCHAR(100),                            -- 权限标识（如 system:user:list）
    icon        VARCHAR(100),                            -- 图标
    sort        INT          NOT NULL DEFAULT 0,         -- 排序
    status      SMALLINT     NOT NULL DEFAULT 0,         -- 状态：0=正常，1=禁用
    visible     BOOLEAN      NOT NULL DEFAULT TRUE,      -- 是否可见
    PRIMARY KEY (id)
);

COMMENT ON TABLE system_menu IS '菜单权限表';

CREATE INDEX idx_system_menu_parent_id ON system_menu (parent_id);