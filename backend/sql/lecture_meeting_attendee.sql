-- =============================================================
-- TrueBuddy - 模拟会议参会人表 lecture_meeting_attendee
-- 对应讲课模块 tb-module-lecture（meeting 包）
-- 说明：
--   1. 学生点入会链接 → 弹窗输入名字 → 本表落一行，并签发 attendee_token；
--   2. 老师不参会（走控制台，用 lecture_meeting.host_token 鉴权），role=1 仅作数据完整性预留；
--   3. online 落库但实时连接态不落库：进程重启后按「全部离线」处理。
-- =============================================================

CREATE TABLE IF NOT EXISTS lecture_meeting_attendee (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    meeting_id     BIGINT      NOT NULL,                    -- 会议 id（逻辑外键 lecture_meeting.id）
    nickname       VARCHAR(64) NOT NULL,                    -- 参会昵称（同一会议内自动去重）
    attendee_token VARCHAR(64) NOT NULL,                    -- 参会凭据（会议内身份，WebSocket 握手校验）
    role           SMALLINT    NOT NULL DEFAULT 2,          -- 角色：1=老师，2=学生
    online         BOOLEAN     NOT NULL DEFAULT TRUE,       -- 是否在线
    join_time      TIMESTAMP   NOT NULL DEFAULT now(),      -- 入会时间
    leave_time     TIMESTAMP,                               -- 离会时间
    create_time    TIMESTAMP   NOT NULL DEFAULT now(),      -- 创建时间
    update_time    TIMESTAMP   NOT NULL DEFAULT now(),      -- 更新时间
    creator        BIGINT,                                  -- 创建人 id
    updater        BIGINT,                                  -- 更新人 id
    deleted        BOOLEAN     NOT NULL DEFAULT FALSE,      -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE  lecture_meeting_attendee IS '模拟会议参会人表（学生入会一行）';
COMMENT ON COLUMN lecture_meeting_attendee.meeting_id IS '会议 id（逻辑外键 lecture_meeting.id）';
COMMENT ON COLUMN lecture_meeting_attendee.nickname IS '参会昵称（同一会议内重名自动加后缀）';
COMMENT ON COLUMN lecture_meeting_attendee.attendee_token IS '参会凭据（会议内身份，WebSocket 握手与上行消息校验）';
COMMENT ON COLUMN lecture_meeting_attendee.role IS '角色：1=老师，2=学生';
COMMENT ON COLUMN lecture_meeting_attendee.online IS '是否在线（进程重启后全部重置为离线）';
COMMENT ON COLUMN lecture_meeting_attendee.join_time IS '入会时间';
COMMENT ON COLUMN lecture_meeting_attendee.leave_time IS '离会时间';

CREATE INDEX IF NOT EXISTS idx_lecture_meeting_attendee_meeting
    ON lecture_meeting_attendee (meeting_id) WHERE deleted = FALSE;

CREATE UNIQUE INDEX IF NOT EXISTS uk_lecture_meeting_attendee_token
    ON lecture_meeting_attendee (attendee_token) WHERE deleted = FALSE;
