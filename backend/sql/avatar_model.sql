-- =============================================================
-- TrueBuddy - 数字人形象目录表 avatar_model
-- 对应讲课模块 tb-module-lecture（PPT 数字人设置）
-- 说明：
--   1. 本表只做目录：哪些形象可展示、显示名、缩略图、排序、启停；
--      模型地址与取景参数仍由前端 frontend/src/views/ppt/configs/avatar.js 维护；
--   2. model_code 必须与前端 AVATAR_MODELS 的键一致，前端按它加载 Live2D；
--   3. 软删用 deleted 布尔列（与 lecture_meeting 一致）；creator / updater 为逻辑外键。
-- =============================================================

CREATE TABLE IF NOT EXISTS avatar_model (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 主键（自增）
    model_code    VARCHAR(50)  NOT NULL,                   -- 形象编码，与前端 configs/avatar.js 的键一致
    name          VARCHAR(50)  NOT NULL,                   -- 显示名称
    kind          VARCHAR(20)  NOT NULL DEFAULT 'sample',  -- 类型：deepseek=社区二创，sample=Live2D 官方示例
    preview_image VARCHAR(255),                            -- 静态缩略图路径（public 下的绝对路径）
    sort          INT          NOT NULL DEFAULT 0,         -- 排序（升序）
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,      -- 是否在设置弹窗中展示
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 创建时间
    update_time   TIMESTAMP    NOT NULL DEFAULT now(),     -- 更新时间
    creator       BIGINT,                                  -- 创建人 id
    updater       BIGINT,                                  -- 更新人 id
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE,     -- 是否删除：false=否，true=是
    PRIMARY KEY (id)
);

COMMENT ON TABLE  avatar_model IS '数字人形象目录（Live2D 模型的可展示清单）';
COMMENT ON COLUMN avatar_model.model_code IS '形象编码，与前端 configs/avatar.js 的键一致';
COMMENT ON COLUMN avatar_model.name IS '显示名称';
COMMENT ON COLUMN avatar_model.kind IS '类型：deepseek=社区二创，sample=Live2D 官方示例';
COMMENT ON COLUMN avatar_model.preview_image IS '静态缩略图路径（public 下的绝对路径）';
COMMENT ON COLUMN avatar_model.sort IS '排序（升序）';
COMMENT ON COLUMN avatar_model.enabled IS '是否在设置弹窗中展示';

CREATE UNIQUE INDEX IF NOT EXISTS uk_avatar_model_code ON avatar_model (model_code);
CREATE INDEX IF NOT EXISTS idx_avatar_model_enabled_sort ON avatar_model (enabled, sort) WHERE deleted = FALSE;

